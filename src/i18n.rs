#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Language {
    #[default]
    PtBr,

    EnUs,

    EsEs,
}

/// Runtime-shared current language, readable from independent async backend
/// tasks that don't otherwise have access to `App`. Cheap to clone (Arc) and
/// updated whenever the user switches language in the config modal.
#[derive(Debug, Clone)]
pub struct SharedLang(std::sync::Arc<std::sync::atomic::AtomicU8>);

impl SharedLang {
    pub fn new(lang: Language) -> Self {
        Self(std::sync::Arc::new(std::sync::atomic::AtomicU8::new(
            lang.as_u8(),
        )))
    }

    pub fn get(&self) -> Language {
        Language::from_u8(self.0.load(std::sync::atomic::Ordering::Relaxed))
    }

    pub fn set(&self, lang: Language) {
        self.0
            .store(lang.as_u8(), std::sync::atomic::Ordering::Relaxed);
    }

    pub fn messages(&self) -> &'static Messages {
        self.get().messages()
    }
}

impl Default for SharedLang {
    fn default() -> Self {
        Self::new(Language::default())
    }
}

impl Language {
    pub fn parse(raw: &str) -> Option<Self> {
        let clean = raw.trim().to_lowercase().replace('_', "-");
        if clean.starts_with("pt") {
            Some(Language::PtBr)
        } else if clean.starts_with("en") {
            Some(Language::EnUs)
        } else if clean.starts_with("es") {
            Some(Language::EsEs)
        } else {
            None
        }
    }

    pub fn detect() -> Self {
        for var in ["LC_ALL", "LC_MESSAGES", "LANG"] {
            if let Ok(val) = std::env::var(var) {
                if let Some(lang) = Self::parse(&val) {
                    return lang;
                }
            }
        }
        Language::PtBr
    }

    pub const fn code(self) -> &'static str {
        match self {
            Language::PtBr => "pt-BR",
            Language::EnUs => "en-US",
            Language::EsEs => "es-ES",
        }
    }

    pub const fn name(self) -> &'static str {
        match self {
            Language::PtBr => "Português (Brasil)",
            Language::EnUs => "English (US)",
            Language::EsEs => "Español",
        }
    }

    pub const fn messages(self) -> &'static Messages {
        match self {
            Language::PtBr => &MESSAGES_PT_BR,
            Language::EnUs => &MESSAGES_EN_US,
            Language::EsEs => &MESSAGES_ES_ES,
        }
    }

    pub const fn as_u8(self) -> u8 {
        match self {
            Language::PtBr => 0,
            Language::EnUs => 1,
            Language::EsEs => 2,
        }
    }

    pub const fn from_u8(raw: u8) -> Self {
        match raw {
            1 => Language::EnUs,
            2 => Language::EsEs,
            _ => Language::PtBr,
        }
    }
}

